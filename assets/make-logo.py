#!/usr/bin/env python3
"""Generates assets/icon.svg and assets/icon-small.svg: a 16x16 pixel creeper face in
violet, purple and blue. Run assets/build-icons.sh afterwards for the PNG/ICO/ICNS files."""
import pathlib
import random

HERE = pathlib.Path(__file__).parent

# Creeper face on an 8x8 grid (each cell = 2x2 pixels); 1 = face.
FACE = [
    "00000000",
    "00000000",
    "01100110",
    "01100110",
    "00011000",
    "00111100",
    "00111100",
    "00100100",
]

def is_face(x, y):
    return FACE[y // 2][x // 2] == "1"

# Skin shades: blue at the bottom-left through purple to violet at the top-right.
DARK = ["#3b2aa8", "#4b2fc0", "#5a2fd0", "#6a32d8"]
MID = ["#5b5ef0", "#6f4ff2", "#8448f2", "#9a4ff4"]
LIGHT = ["#7d8bff", "#9a7dff", "#b07cff", "#c48cff"]
FACE_COLOR = "#0b0616"
HIGHLIGHT = "#d9c8ff"

def skin(x, y):
    band = min(3, max(0, round((x + (15 - y)) / 30 * 3 + random.uniform(-0.6, 0.6))))
    roll = random.random()
    shades = DARK if roll < 0.25 else LIGHT if roll > 0.78 else MID
    return shades[band]

def svg(radius):
    random.seed(7)  # fixed, so every size and every run gets the same speckles
    rects = []
    for y in range(16):
        for x in range(16):
            if is_face(x, y):
                color = FACE_COLOR
            # Light rim just below and right of the face, like the in-game texture.
            elif (y > 0 and is_face(x, y - 1)) or (x > 0 and is_face(x - 1, y) and not is_face(x, y)):
                color = HIGHLIGHT if (y > 0 and is_face(x, y - 1)) else LIGHT[3]
            else:
                color = skin(x, y)
            rects.append(f'<rect x="{x}" y="{y}" width="1" height="1" fill="{color}"/>')
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" width="512" height="512" '
        'shape-rendering="crispEdges">\n'
        "  <!-- netherNode logo: a creeper face in violet, purple and blue. Generated by make-logo.py. -->\n"
        f'  <defs><clipPath id="r"><rect width="16" height="16" rx="{radius}"/></clipPath></defs>\n'
        '  <g clip-path="url(#r)">\n    ' + "\n    ".join(rects) + "\n  </g>\n</svg>\n"
    )

(HERE / "icon.svg").write_text(svg(radius=2.5))
(HERE / "icon-small.svg").write_text(svg(radius=1.5))
print("wrote icon.svg and icon-small.svg")
